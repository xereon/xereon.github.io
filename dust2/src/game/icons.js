const f = (n) => (Math.round(n * 10) / 10).toString();
function polyPath(p, wantPositive) {
  let a = 0;
  for (let i = 0; i < p.length; i += 2) {
    const j = (i + 2) % p.length;
    a += p[i] * p[j + 1] - p[j] * p[i + 1];
  }
  const pts = [];
  for (let i = 0; i < p.length; i += 2) pts.push([p[i], p[i + 1]]);
  if ((a > 0) !== wantPositive) pts.reverse();
  return 'M' + pts.map(([x, y]) => f(x) + ' ' + f(y)).join('L') + 'Z';
}
const circPath = (x, y, r, positive) =>
  `M${f(x - r)} ${f(y)}a${f(r)} ${f(r)} 0 1 ${positive ? 1 : 0} ${f(2 * r)} 0a${f(r)} ${f(r)} 0 1 ${positive ? 1 : 0} ${f(-2 * r)} 0Z`;
function rrPath(x, y, w, h, r) {
  r = Math.min(r, w / 2, h / 2);
  return `M${f(x + r)} ${f(y)}H${f(x + w - r)}A${f(r)} ${f(r)} 0 0 1 ${f(x + w)} ${f(y + r)}V${f(y + h - r)}A${f(r)} ${f(r)} 0 0 1 ${f(x + w - r)} ${f(y + h)}H${f(x + r)}A${f(r)} ${f(r)} 0 0 1 ${f(x)} ${f(y + h - r)}V${f(y + r)}A${f(r)} ${f(r)} 0 0 1 ${f(x + r)} ${f(y)}Z`;
}

function renderShapes(shapes) {
  let fill = '', out = '';
  const strokes = [];
  for (const s of shapes) {
    switch (s.t) {
      case 'p': fill += polyPath(s.p, true); break;
      case 'h': fill += polyPath(s.p, false); break;
      case 'c': fill += circPath(s.x, s.y, s.r, true); break;
      case 'ch': fill += circPath(s.x, s.y, s.r, false); break;
      case 'rr': fill += rrPath(s.x, s.y, s.w, s.h, s.r); break;
      case 'r': fill += s.d; break; // raw paths are authored clockwise (= body winding)
      case 'l': strokes.push(s); break;
      case 'g': out += `<g opacity="${s.o}" transform="translate(${s.dx} ${s.dy})">${renderShapes(s.s)}</g>`; break;
    }
  }
  if (fill) out = `<path d="${fill}"/>` + out;
  for (const s of strokes) {
    let d = '';
    for (let i = 0; i < s.p.length; i += 2) d += (i ? 'L' : 'M') + f(s.p[i]) + ' ' + f(s.p[i + 1]);
    out += `<path d="${d}" fill="none" stroke="currentColor" stroke-width="${s.w}" stroke-linejoin="round" stroke-linecap="round"/>`;
  }
  return out;
}

const cache = new Map();
/**
 * SVG markup for an icon, sized to `h` em tall (width follows the aspect ratio).
 * Unknown keys fall back to a neutral bullet glyph so the UI never shows a hole.
 */
export function icon(key, cls = '', h = 1) {
  const ck = key + '|' + cls + '|' + h;
  const hit = cache.get(ck);
  if (hit) return hit;
  const def = I[key] || G[key] || G.bullets;
  const w = def.w;
  const svg = `<svg class="ic ${cls}" viewBox="0 0 ${w} 64" width="${f((w / 64) * h)}em" height="${h}em" fill="currentColor" aria-hidden="true">${renderShapes(def.s)}</svg>`;
  cache.set(ck, svg);
  return svg;
}
