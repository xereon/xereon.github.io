// Original SVG silhouettes for weapons, equipment and HUD glyphs (not Valve's icon set).
// Weapons face right (muzzle on the right) on a 64-unit-high canvas; width varies per gun
// so every icon can be rendered at a fixed height (kill feed, buy menu, inventory).
//
// Shapes: poly(...xy) filled body, hole(...xy) cut-out, circ/chole circles, line(w, ...xy)
// stroked polyline, rr(x,y,w,h,r) rounded rect, raw(d) path. Bodies are normalised to one
// winding and holes to the other, so one nonzero-filled <path> unions bodies minus holes.

const poly = (...p) => ({ t: 'p', p });
const hole = (...p) => ({ t: 'h', p });
const circ = (x, y, r) => ({ t: 'c', x, y, r });
const chole = (x, y, r) => ({ t: 'ch', x, y, r });
const line = (w, ...p) => ({ t: 'l', w, p });
const raw = (d) => ({ t: 'r', d });
const rect = (x, y, w, h) => poly(x, y, x + w, y, x + w, y + h, x, y + h);
const rhole = (x, y, w, h) => hole(x, y, x + w, y, x + w, y + h, x, y + h);
const rr = (x, y, w, h, r) => ({ t: 'rr', x, y, w, h, r });
const group = (opacity, shapes, dx = 0, dy = 0) => ({ t: 'g', o: opacity, s: shapes, dx, dy });

// ---- shared parts ---------------------------------------------------------------------------
const guard = (x, y, w = 16, d = 9) => line(3.2, x, y, x + 2, y + d, x + w - 2, y + d, x + w + 2, y);
const pgrip = (x, y, w = 15, h = 23, rake = 5) => poly(x, y, x + w, y, x + w - rake, y + h, x - rake + 1, y + h, x - rake - 1, y + h - 4);

